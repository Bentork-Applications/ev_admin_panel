import { safeDecodeJwt } from "./jwtUtils";

/**
 * Dynamically retrieves the currently authenticated user's name/email/identity
 * and returns a clean uppercase watermark string.
 * Fallback is 'ADMIN'.
 *
 * @returns {string} Uppercase watermark text
 */
export const getExportWatermark = () => {
  try {
    let name = "";
    let email = "";

    // 1. Try reading from localStorage "user" object if available
    try {
      const storedUser = JSON.parse(localStorage.getItem("user") || "{}");
      if (storedUser && typeof storedUser === "object") {
        name = storedUser.name || storedUser.displayName || storedUser.fullName || storedUser.username || "";
        email = storedUser.email || "";
      }
    } catch {
      // Ignore JSON parse errors
    }

    // 2. Try decoding JWT token if name/email are still missing
    const token = localStorage.getItem("token");
    if (token) {
      const payload = safeDecodeJwt(token);
      if (payload) {
        if (!name) {
          name = payload.name || payload.displayName || payload.fullName || payload.username || "";
        }
        if (!email) {
          email = payload.email || payload.sub || "";
        }
      }
    }

    const cleanName = (name || "").trim();
    const cleanEmail = (email || "").trim();

    if (cleanName) {
      return cleanName.toUpperCase();
    }
    if (cleanEmail) {
      return cleanEmail.toUpperCase();
    }
    return "ADMIN";
  } catch (err) {
    console.error("Error evaluating export watermark:", err);
    return "ADMIN";
  }
};

/**
 * Returns a standard export metadata line for CSV/Excel export files.
 * Example: "Generated By: SWAPNIL JADHAV | Generated At: 24 Aug 2026, 01:15 PM"
 *
 * @returns {string} Metadata string
 */
export const getExportMetadataHeader = () => {
  const userStr = getExportWatermark();
  const dateStr = new Date().toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: true
  });
  return `Generated By: ${userStr} | Generated At: ${dateStr}`;
};

/**
 * Returns HTML and CSS snippet for a rotated, low-opacity background watermark
 * suitable for PDF / print report documents.
 *
 * @returns {string} HTML string overlay
 */
export const getPdfWatermarkHtml = (customText) => {
  const user = getExportWatermark();
  const watermarkText = customText || (user.toUpperCase().startsWith("GENERATED BY") ? user : `GENERATED BY: ${user}`);
  return `
    <div class="watermark-overlay" style="
      position: fixed;
      top: 50%;
      left: 50%;
      transform: translate(-50%, -50%) rotate(-30deg);
      font-size: 46px;
      font-weight: 800;
      color: rgba(0, 0, 0, 0.06);
      white-space: nowrap;
      pointer-events: none;
      z-index: 9999;
      user-select: none;
      font-family: Arial, sans-serif;
      letter-spacing: 3px;
      text-transform: uppercase;
    ">
      ${watermarkText}
    </div>
  `;
};
